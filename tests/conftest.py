"""Shared test fixtures: project paths and the saved PBMC3k reference outputs.

Reference outputs are read from `validation/expected/` (generated by
`reference/scrna-seq-validated.ipynb`). Tests never re-run the notebook. If a file is
missing, the test fails with instructions instead of regenerating anything.
"""

from __future__ import annotations

import json
from pathlib import Path

import anndata as ad
import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent
RAW_DATA = PROJECT_ROOT / "data" / "pbmc3k.h5ad"
MOUSE_10X = PROJECT_ROOT / "data" / "neuron_1k_v3_filtered_feature_bc_matrix.h5"
KANG = PROJECT_ROOT / "data" / "kang_2018.h5ad"
EXPECTED_DIR = PROJECT_ROOT / "validation" / "expected"

REGENERATE_HINT = (
    "Regenerate it (with approval) by executing the validated notebook:\n"
    "  jupyter nbconvert --to notebook --execute --inplace reference/scrna-seq-validated.ipynb\n"
    "See 'Regenerating the reference outputs' in CLAUDE.md."
)


def _require(path: Path) -> Path:
    if not path.is_file():
        pytest.fail(f"Missing reference file: {path.relative_to(PROJECT_ROOT)}\n{REGENERATE_HINT}")
    return path


@pytest.fixture(scope="session")
def raw_data_path() -> Path:
    """The raw PBMC3k input file."""
    if not RAW_DATA.is_file():
        pytest.fail(f"Missing input data: {RAW_DATA}. Run scripts/download_pbmc3k.py.")
    return RAW_DATA


@pytest.fixture(scope="session")
def mouse_10x_path() -> Path:
    """The second test dataset: 10x "1k Brain Cells from an E18 Mouse" (.h5). Used only to
    check that the app works beyond PBMC3k (another species, tissue and file format)."""
    if not MOUSE_10X.is_file():
        pytest.fail(f"Missing test data: {MOUSE_10X}. Run scripts/download_test_data.py.")
    return MOUSE_10X


@pytest.fixture(scope="session")
def kang_path() -> Path:
    """The multiple-samples test dataset: Kang et al. 2018 PBMCs (8 patients, control vs
    interferon-beta; raw counts). Used only to check loading and analyzing several samples."""
    if not KANG.is_file():
        pytest.fail(f"Missing test data: {KANG}. Run scripts/download_kang_data.py.")
    return KANG


@pytest.fixture(scope="session")
def reference_summary() -> dict:
    """`validation/expected/reference_summary.json`, loaded once per test session."""
    path = _require(EXPECTED_DIR / "reference_summary.json")
    return json.loads(path.read_text())


@pytest.fixture(scope="session")
def scaled_pbmc3k(raw_data_path) -> ad.AnnData:
    """PBMC3k after the already-validated steps (load, QC, filter, preprocessing) with
    the reference preset. Starting point for later modules. Treat as read-only."""
    from scrna_analysis.load_data import load_h5ad
    from tests.reference_preset import REFERENCE_PRESET as P
    from scrna_analysis.preprocessing import (
        find_hvgs, keep_raw_and_subset, normalize_and_log, regress_and_scale,
    )
    from scrna_analysis.qc import apply_filter, calculate_qc_metrics

    adata, _ = load_h5ad(raw_data_path)
    adata, _ = calculate_qc_metrics(adata, P.qc)
    adata, _ = apply_filter(adata, P.filter)
    adata, _ = normalize_and_log(adata, P.normalize)
    adata, _ = find_hvgs(adata, P.hvg)
    adata, _ = keep_raw_and_subset(adata)
    adata, _ = regress_and_scale(adata, P.regress_out, P.scale)
    return adata


